    def _pretty_action_label(raw: str) -> str:
        s = str(raw or "").strip()
        # common patterns: "xxx：开关" / "xxx: 开关"
        s = s.replace("：开关", "").replace(": 开关", "").replace(":开关", "")
        return s

    def _emit_class(
        *,
        base_class_name: str,
        template: str,
        complexity: int,
        params: dict[str, Any],
        optimal_paths: list,
        judge: dict[str, Any],
        add_discover_sampler: bool,
    ) -> list[str]:
        out: list[str] = []
        out.append(f"\n\nclass {base_class_name}(_WechatActionTaskBase):")
        out.append(f"    template = {template!r}")
        out.append("    app = 'wechat_action_tasks'")
        out.append(f"    complexity = {int(complexity)}")
