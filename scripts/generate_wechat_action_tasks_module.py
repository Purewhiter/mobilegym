#!/usr/bin/env python3
"""
Generate explicit (one-by-one) WeChat action tasks as Python classes.

Input:
  bench_env/generated_task/action_tasks/spec.jsonl
  (generated by scripts/build_action_task_specs.py)

Output:
  bench_env/generated_task/wechat_action_tasks/tasks.py

Why:
  User asked to "一个个写出这些任务"，先写微信，并且必须是 state judge（不是 VLM）。

Notes:
  Some action ids only affect local React component state (not exposed in __SIM__.getState()
  and not changing route). Those are NOT judgeable via state/route, so we skip them.
"""

from __future__ import annotations

import json
import re
import pprint
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
SPEC_PATH = ROOT / "bench_env/generated_task/action_tasks/spec.jsonl"
OUT_PATH = ROOT / "bench_env/generated_task/wechat_action_tasks/tasks.py"


SKIP_ACTION_IDS = {
    # Only updates local component state (pin dots), no route/state change.
    "faceToFace.pin.input",
    "faceToFace.pin.delete.submit",
}


PAREN_RE = re.compile(r"[（(]([^）)]+)[）)]")


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = (line or "").strip()
        if not line:
            continue
        obj = json.loads(line)
        if isinstance(obj, dict):
            out.append(obj)
    return out


def extract_expected_from_label(label: str) -> str | None:
    if not label:
        return None
    m = PAREN_RE.findall(label)
    if not m:
        return None
    return (m[-1] or "").strip() or None


def infer_wechat_judge(spec: dict[str, Any]) -> dict[str, Any]:
    action = spec.get("action") if isinstance(spec.get("action"), dict) else {}
    action_id = str(action.get("id") or "")
    behavior = str(action.get("behavior") or "")
    label = str(action.get("label") or "")

    # 1) Chat actions
    if action_id == "chat.pat.send":
        return {"kind": "wechat_chat_pat", "id_param": "id"}

    if behavior == "toggle":
        if action_id.startswith("chatInfo.item.") and action_id.endswith(".toggle"):
            key = action_id[len("chatInfo.item.") : -len(".toggle")]
            field_map = {"muted": "isMuted", "sticky": "isSticky", "alert": "isAlert"}
            field = field_map.get(key)
            if field:
                return {"kind": "toggle_chat_field", "id_param": "id", "field": field}

        if action_id.startswith("friendSettings.item.") and action_id.endswith(".toggle"):
            key = action_id[len("friendSettings.item.") : -len(".toggle")]
            field_map = {"star": "isStarred", "blacklist": "isBlacklisted"}
            field = field_map.get(key)
            if field:
                return {"kind": "toggle_contact_field", "id_param": "id", "field": field}

        if action_id.startswith("friendPermissionsDetail.item.") and action_id.endswith(".toggle"):
            key = action_id[len("friendPermissionsDetail.item.") : -len(".toggle")]
            field_map = {"hideMyMoments": "hideMyMoments", "hideTheirMoments": "hideTheirMoments"}
            field = field_map.get(key)
            if field:
                return {"kind": "toggle_contact_field", "id_param": "id", "field": field}

        if action_id.startswith("wechatSports.") and action_id.endswith(".toggle"):
            rest = action_id[len("wechatSports.") : -len(".toggle")]
            parts = [p for p in rest.split(".") if p]
            if parts and parts[0] == "privacy":
                parts = parts[1:]
            if parts:
                return {"kind": "toggle_field", "path": "user.settings.accessibility.wechatSports." + ".".join(parts)}

        if action_id.startswith("settings.") and action_id.endswith(".toggle"):
            core = action_id[len("settings.") : -len(".toggle")]
            parts = [p for p in core.split(".") if p]
            if not parts:
                return {"kind": "state_diff", "prefix": "user.settings"}
            section = parts[0]
            tail = parts[1:]

            if section == "accessibility" and len(tail) >= 2:
                # settings.accessibility.tencentNews.dnd.toggle -> user.settings.accessibility.tencentNews.dnd
                plugin = tail[0]
                field = ".".join(tail[1:])
                return {"kind": "toggle_field", "path": f"user.settings.accessibility.{plugin}.{field}"}

            if section == "discover" and tail[:1] == ["item"] and len(tail) >= 2:
                # settings.discover.item.visible.toggle -> user.settings.discover[id].visible
                field = tail[1]
                return {"kind": "toggle_discover_item_field", "id_param": "id", "field": field}

            if section == "careMode":
                return {"kind": "toggle_field", "path": "user.settings.modes.care"}
            if section == "minorMode":
                return {"kind": "toggle_field", "path": "user.settings.modes.minor"}

            if section == "privacy":
                if tail[:1] == ["addMe"] and len(tail) >= 2:
                    return {"kind": "toggle_field", "path": f"user.settings.privacy.addMeMethods.{tail[1]}"}
                if tail == ["moments", "strangerTen"]:
                    return {"kind": "toggle_field", "path": "user.settings.privacy.momentsStrangerTen"}
                if tail:
                    return {"kind": "toggle_field", "path": "user.settings.privacy." + ".".join(tail)}
                return {"kind": "state_diff", "prefix": "user.settings.privacy"}

            if section == "general" and tail:
                if tail[:2] == ["darkMode", "followSystem"]:
                    return {"kind": "toggle_field", "path": "user.settings.general.followSystem"}
                if tail[:2] == ["translation", "autoTranslate"]:
                    return {"kind": "toggle_field", "path": "user.settings.general.autoTranslate"}
                if tail[:1] in (["media"], ["audio"]) and len(tail) >= 2:
                    return {"kind": "toggle_field", "path": "user.settings.general." + ".".join(tail[1:])}
                return {"kind": "toggle_field", "path": "user.settings.general." + ".".join(tail)}

            if section == "chat" and tail:
                return {"kind": "toggle_field", "path": "user.settings.chat." + ".".join(tail)}

            if section == "notifications" and tail:
                return {"kind": "toggle_field", "path": "user.settings.notifications." + ".".join(tail)}

            return {"kind": "state_diff", "prefix": "user.settings"}

    if behavior == "select":
        expected = extract_expected_from_label(label)
        if action_id.startswith("settings.notifications.sound.select.") and expected:
            return {"kind": "set_field", "path": "user.settings.notifications.notificationSound", "expected": expected}
        if action_id.startswith("settings.notifications.incomingRingtone.select.") and expected:
            return {"kind": "set_field", "path": "user.settings.notifications.incomingRingtone", "expected": expected}
        if action_id.startswith("settings.privacy.moments.range.select.") and expected:
            return {"kind": "set_field", "path": "user.settings.privacy.momentsRange", "expected": expected}
        if action_id.startswith("settings.general.darkMode.mode.select."):
            if "深色" in label:
                return {"kind": "multi_set", "checks": [
                    {"path": "user.settings.general.followSystem", "expected": False},
                    {"path": "user.settings.general.darkMode", "expected": True},
                ]}
            if "普通" in label:
                return {"kind": "multi_set", "checks": [
                    {"path": "user.settings.general.followSystem", "expected": False},
                    {"path": "user.settings.general.darkMode", "expected": False},
                ]}
        return {"kind": "state_diff", "prefix": "user.settings"}

    # submit/input/other: handle known ones
    if action_id == "friendSettings.menu.blacklistConfirm.submit":
        return {"kind": "set_contact_field", "id_param": "id", "field": "isBlacklisted", "expected": True}

    if action_id == "settings.privacy.authorization.menu.confirm.submit":
        return {"kind": "remove_authorized_app", "id_param": "id"}

    if action_id.endswith(".enable.submit") and action_id.startswith("settings.accessibility."):
        # settings.accessibility.wechatSports.enable.submit -> enabled=True
        core = action_id[len("settings.accessibility.") : -len(".enable.submit")]
        return {"kind": "set_field", "path": f"user.settings.accessibility.{core}.enabled", "expected": True}

    if action_id.endswith(".disable.submit") and action_id.startswith("settings.accessibility."):
        core = action_id[len("settings.accessibility.") : -len(".disable.submit")]
        return {"kind": "set_field", "path": f"user.settings.accessibility.{core}.enabled", "expected": False}

    if action_id in {"moments.post.submit", "moments.postText.submit"}:
        return {"kind": "list_len_increased", "path": "moments"}

    if action_id in {"profile.name.submit"}:
        return {"kind": "field_changed", "path": "user.name"}
    if action_id in {"profile.signature.submit"}:
        return {"kind": "field_changed", "path": "user.signature"}
    if action_id in {"profile.gender.submit"}:
        return {"kind": "field_changed", "path": "user.gender"}
    if action_id in {"profile.pat.submit"}:
        return {"kind": "field_changed", "path": "user.pat"}

    if action_id in {"settings.notifications.sound.submit"}:
        return {"kind": "field_changed", "path": "user.settings.notifications.notificationSound"}

    if action_id in {"settings.general.darkMode.submit"}:
        return {"kind": "state_diff", "prefix": "user.settings.general"}

    # last resort (still state-based, but weaker)
    return {"kind": "state_diff", "prefix": ""}  # any app-state diff


